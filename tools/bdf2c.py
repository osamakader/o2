#!/usr/bin/env python3
# bdf2c.py font.bdf [LICENSE] > font.h: an 8-pixel-wide BDF font's printable
# ASCII (32-126) as a C array, one byte per row (bit 7 the leftmost
# pixel). The BDF's comments (its copyright) come along, and the
# licence file's text.

import sys


def main():
    lines = open(sys.argv[1]).read().splitlines()
    comments, glyphs = [], {}
    w = h = descent = 0
    i = 0
    while i < len(lines):
        f = lines[i].split()
        if f and f[0] == "COMMENT":
            comments.append(lines[i][8:])
        elif f and f[0] == "FONTBOUNDINGBOX":
            w, h, descent = int(f[1]), int(f[2]), -int(f[4])
        elif f and f[0] == "ENCODING":
            code = int(f[1])
        elif f and f[0] == "BBX":
            bw, bh, bx, by = map(int, f[1:5])
        elif f and f[0] == "BITMAP":
            rows = [int(r, 16) for r in lines[i + 1:i + 1 + bh]]
            # place the glyph's box in the font's cell
            cell = [0] * h
            top = h - descent - by - bh
            for j, r in enumerate(rows):
                if 0 <= top + j < h:
                    cell[top + j] = (r >> bx) & 0xff
            glyphs[code] = cell
            i += bh
        i += 1
    if w != 8:
        sys.exit("bdf2c: only 8-pixel-wide fonts")

    print("// Generated by tools/bdf2c.py from %s; do not edit." % sys.argv[1].split("/")[-1])
    text = [c.replace("/*", "").replace("*/", "").replace(" * ", " ", 1).rstrip(" *") for c in comments]
    if len(sys.argv) > 2:
        while text and not text[-1].strip():
            text.pop()
        text += [""] + [" " + l if l else "" for l in open(sys.argv[2]).read().splitlines()]
    while text and not text[0].strip():
        text.pop(0)
    print("//")
    for t in text:
        print("//" + t.rstrip())
    print()
    print("#define FONT_W %d" % w)
    print("#define FONT_H %d" % h)
    print()
    print("// glyphs for characters 32 to 126, FONT_H rows each")
    print("static const unsigned char font[95][FONT_H] = {")
    for code in range(32, 127):
        cell = glyphs.get(code, [0] * h)
        print("  { %s }, // %r" % (", ".join("0x%02x" % r for r in cell), chr(code)))
    print("};")


main()
